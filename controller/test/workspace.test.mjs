test('failed capture preserves real source and ignored outputs without importing tooling symlinks', async t => {
  const root=await mkdtemp(join(tmpdir(),'nibfin-failed-capture-'));
  t.after(()=>rm(root,{recursive:true,force:true}));
  const seed=join(root,'seed');await mkdir(seed);
  const git=async args=>(await command('git',args,{cwd:seed})).stdout.trim();
  await git(['init']);await git(['config','user.name','Fixture']);await git(['config','user.email','fixture@example.test']);
  await writeFile(join(seed,'.gitignore'),'node_modules/\nout/\n');
  await writeFile(join(seed,'source.mjs'),'original\n');await git(['add','.']);await git(['commit','-m','base']);
  const base=await git(['rev-parse','HEAD']),remote=join(root,'remote.git');await git(['clone','--bare',seed,remote]);
  const run=(exe,args,options)=>command(exe,args.map(a=>a==='https://github.com/example/one.git'?remote:a),options);
  const issue={id:'I_1',repository:'example/one',number:1,scopeHash:digest('old Scope')},source=new Workspace(join(root,'source'),issue,'fixture',run);
  await source.prepare(base);await writeFile(join(source.work,'source.mjs'),'implementation\n');
  await mkdir(join(source.work,'node_modules/.bin'),{recursive:true});
  await symlink('../yaml/bin.mjs',join(source.work,'node_modules/.bin/yaml'));
  await mkdir(join(source.work,'out'));await writeFile(join(source.work,'out/package.tgz'),'exact package bytes');
  const obligations={artifacts:[{path:'out/package.tgz',purpose:'package'},{path:'out/missing.txt',purpose:'required proof'}],hooks:[]};
  await assert.rejects(source.capture(base,true,obligations),/Symlinks/);
  const shape='```nibfin-candidate\n'+JSON.stringify(obligations)+'\n```';
  const old={issues:{I_1:{repairs:0,shape:{base,body:shape,bodyHash:digest(shape)},accept:{outcome:'accepted'}}}};
  const saved=await preserveScopeImplementation({config:{stateDirectory:root},workspaceFactory:()=>source},issue,'dynamic:'+'1'.repeat(64),old,null);
  const seedRecord={...saved,targetAttempt:1};
  assert.equal(saved.sourceScopeHash,issue.scopeHash);assert.equal(saved.accept,undefined);
  assert.equal(saved.unaccepted,true);assert.deepEqual(saved.missingOutputs,[{kind:'artifacts',path:'out/missing.txt'}]);
  assert.ok(saved.candidate.paths.includes('source.mjs'));
  const target=new Workspace(join(root,'target'),issue,'fixture',run);
  await target.restoreRepair(source,seedRecord,base);
  assert.notEqual(await target.fetchedBase(),base,'repair seed fetch must reproduce the changed FETCH_HEAD');
  assert.equal(await target.preparedBase(),base,'prepared delivery base survives the repair seed fetch');
  assert.equal(await readFile(join(target.work,'source.mjs'),'utf8'),'implementation\n');
  assert.equal(await readFile(join(target.work,'out/package.tgz'),'utf8'),'exact package bytes');
  await assert.rejects(lstat(join(target.work,'node_modules')),{code:'ENOENT'});
  assert.ok((await lstat(join(source.work,'node_modules/.bin/yaml'))).isSymbolicLink());
  // The partial snapshot cannot satisfy the unchanged full output contract.
  await assert.rejects(target.capture(base,true,obligations),{code:'ENOENT'});
  await symlink('source.mjs',join(source.work,'tracked-link'));
  await assert.rejects(source.snapshotRepair(base,obligations),/regular source files/);
  await rm(join(source.work,'tracked-link'));
  await mkdir(join(root,'outside'));await writeFile(join(root,'outside/secret'),'must not import');
  await symlink(join(root,'outside'),join(source.work,'out/escape'),'dir');
  await assert.rejects(source.snapshotRepair(base,{artifacts:[{path:'out/escape/secret',purpose:'escape'}],hooks:[]}),/symlink/);
});

