import { readFile } from 'node:fs/promises';
import { Runtime } from '../src/runtime.mjs';
import { readBindings } from '../src/runner-binding.mjs';
import { dependencyWebhookSecret } from '../src/dependency-event.mjs';
import { fileURLToPath } from 'node:url';
const [configPath,policyPath,repository,url] = process.argv.slice(2);
if (!url || new URL(url).protocol !== 'https:' || new URL(url).pathname !== '/dependency-event') throw Error('Explicit HTTPS dependency-event URL required');
const runtime = await Runtime.connect(configPath,fileURLToPath(new URL('..',import.meta.url)));
const policy=JSON.parse(await readFile(policyPath,'utf8'));
const entry=(await readBindings(runtime.config,policy))[repository];
if(!entry || !policy.actionEvents?.[repository]) throw Error('Repository not enrolled');
const root='/repos/'+repository+'/hooks';
const hooks=await runtime.github.list(root);
const matches=hooks.filter(h=>h.config?.url===url);
if(matches.length>1)throw Error('Ambiguous webhook enrollment');
const body={name:'web',active:true,events:['issue_dependencies'],config:{url,content_type:'json',insecure_ssl:'0',secret:dependencyWebhookSecret(entry)}};
const hook=await runtime.github.api(matches.length?root+'/'+matches[0].id:root,matches.length?'PATCH':'POST',body);
console.log(JSON.stringify({repository,hookId:hook.id,active:hook.active,events:hook.events,url}));
