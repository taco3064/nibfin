test('real Git candidate includes additions/deletions, isolated metadata, deterministic commit and safe replay', async t => {
  const root = await mkdtemp(join(tmpdir(), 'nibfin-git-'));
  t.after(() => rm(root, { recursive: true }));
  const seed = join(root, 'seed'); await mkdir(seed);
  const git = async args => (await command('git', args, { cwd: seed })).stdout.trim();
  await git(['init']); await git(['config', 'user.name', 'Fixture']); await git(['config', 'user.email', 'fixture@example.test']);
  await writeFile(join(seed, 'old.txt'), 'baseline\n');
  await git(['add', '.']); await git(['commit', '-m', 'baseline']);
  const base = await git(['rev-parse', 'HEAD']);
  const remote = join(root, 'remote.git'); await git(['clone', '--bare', seed, remote]);
  const runner = async (exe, args, options) => {
    const safeArgs = args.map(arg => arg === 'https://github.com/example/one.git' ? remote : arg);
    return command(exe, safeArgs, options);
  };
  const workspace = new Workspace(join(root, 'execution'), { repository: 'example/one', number: 1 }, 'fixture-token', runner);
  await workspace.prepare(base);
  assert.equal(await readFile(join(workspace.work, 'old.txt'), 'utf8'), 'baseline\n');
  await assert.rejects(stat(join(workspace.work, '.git')), { code: 'ENOENT' });
  await rm(join(workspace.work, 'old.txt'));
  await writeFile(join(workspace.work, 'new.txt'), 'new\n');
  const candidate = await workspace.capture(base);
  const provenance = await workspace.provenance(base, candidate.tree);
  assert.equal(provenance.tree,candidate.tree);
  assert.deepEqual(provenance.entries.map(e=>e.path),['new.txt']);
  assert.equal(provenance.entries[0].oid,createHash('sha1').update('blob 4\0new\n').digest('hex'));
  assert.deepEqual(candidate.paths.sort(), ['new.txt', 'old.txt']);
  const timestamp = '2026-10-19T00:00:00Z';
  const commit = await workspace.commit(candidate, timestamp);
  assert.equal(await workspace.commit(candidate, timestamp), commit);
  await workspace.push(commit, 'nibfin/test'); await workspace.push(commit, 'nibfin/test');
  const branch=await git(['symbolic-ref','--short','HEAD']);
  const merged=await workspace.mergeCommit(candidate,commit,timestamp);
  const competing=await workspace.git(['commit-tree',candidate.tree,'-p',base],'Concurrent external change\n',{GIT_AUTHOR_NAME:'Fixture',GIT_AUTHOR_EMAIL:'fixture@example.test',GIT_COMMITTER_NAME:'Fixture',GIT_COMMITTER_EMAIL:'fixture@example.test'});
  await workspace.push(competing,'external/staged');
  const previousRun=workspace.run;let race=true;
  workspace.run=async(exe,args,opts)=>{if(race&&args.includes('--porcelain')){race=false;await command('git',['--git-dir='+remote,'update-ref','refs/heads/'+branch,competing,base]);}return previousRun(exe,args,opts);};
  await assert.rejects(workspace.advanceBase(merged,branch,base),{code:'BASE_LEASE_REJECTED'});
  assert.equal((await command('git',['--git-dir='+remote,'rev-parse','refs/heads/'+branch])).stdout.trim(),competing);
  await command('git',['--git-dir='+remote,'update-ref','refs/heads/clean',base]);
  await workspace.advanceBase(merged,'clean',base);await workspace.advanceBase(merged,'clean',base);
  assert.equal((await command('git',['--git-dir='+remote,'rev-parse','refs/heads/clean'])).stdout.trim(),merged);
  await writeFile(join(workspace.work,'.gitignore'),'ignored.txt\n');
  await writeFile(join(workspace.work,'ignored.txt'),'first diagnostic content');
  const obligations={artifacts:[{path:'ignored.txt',purpose:'Required generated evidence'}],hooks:[]};
  const artifactCandidate=await workspace.capture(base,false,obligations);
  assert.ok(!artifactCandidate.paths.includes('ignored.txt'));
  assert.equal(artifactCandidate.artifacts[0].sha256,createHash('sha256').update('first diagnostic content').digest('hex'));
  assert.equal(await readFile(join(workspace.root,'artifacts',artifactCandidate.artifacts[0].sha256),'utf8'),'first diagnostic content');
  await workspace.commit(artifactCandidate,timestamp);
  const attempt=await workspace.captureAttempt(base);
  assert.ok(attempt.workspaceFiles.some(f=>f.path==='ignored.txt'));
  await writeFile(join(workspace.work,'ignored.txt'),'changed diagnostic content');
  await assert.rejects(workspace.commit(artifactCandidate,timestamp),/changed after independent acceptance/);
  await assert.rejects(workspace.capture(base,false,{artifacts:[{path:'missing.txt',purpose:'required'}],hooks:[]}),{code:'ENOENT'});
  assert.notEqual((await workspace.captureAttempt(base)).workspaceHash,attempt.workspaceHash);
  await writeFile(join(workspace.work, 'new.txt'), 'tampered\n');
  await assert.rejects(workspace.commit(candidate, timestamp), /changed/);
});

test('queued clean workspace refreshes an advanced base without losing local candidates or repair identity', async t => {
  const root = await mkdtemp(join(tmpdir(), 'nibfin-base-refresh-'));
  t.after(() => rm(root, { recursive: true }));
  const seed = join(root, 'seed'); await mkdir(seed);
  const git = async args => (await command('git', args, {cwd:seed})).stdout.trim();
  await git(['init']); await git(['config','user.name','Fixture']); await git(['config','user.email','fixture@example.test']);
  await writeFile(join(seed,'base.txt'),'one\n'); await git(['add','.']); await git(['commit','-m','one']);
  const one = await git(['rev-parse','HEAD']);
  const run = (exe,args,options) => command(exe,args.map(a => a === 'https://github.com/example/one.git' ? seed : a),options);
  const issue = {repository:'example/one',number:1};
  const clean = new Workspace(join(root,'clean'),issue,'fixture',run);
  const dirty = new Workspace(join(root,'dirty'),issue,'fixture',run);
  await clean.prepare(one); await dirty.prepare(one);
  await writeFile(join(dirty.work,'base.txt'),'candidate\n');
  await writeFile(join(seed,'base.txt'),'two\n'); await writeFile(join(seed,'added.txt'),'new upstream\n');
  await git(['add','.']); await git(['commit','-m','two']); const two = await git(['rev-parse','HEAD']);
  await assert.rejects(dirty.prepare(two),/local changes/);
  assert.equal(await readFile(join(dirty.work,'base.txt'),'utf8'),'candidate\n');
  assert.equal(await dirty.fetchedBase(),one);
  await dirty.git(['add', '--all']);
  await writeFile(join(dirty.work,'base.txt'),'one\n');
  await assert.rejects(dirty.prepare(two),/local changes/);
  assert.match(await dirty.git(['diff','--cached',one,'--']),/candidate/);
  await clean.prepare(two);
  assert.equal(await readFile(join(clean.work,'base.txt'),'utf8'),'two\n');
  assert.equal(await readFile(join(clean.work,'added.txt'),'utf8'),'new upstream\n');
  assert.deepEqual((await clean.capture(two,true)).paths,[]);
  // A later fetch of a repair seed must not redefine the workspace baseline.
  await clean.git(['fetch','--no-tags','origin',one]);
  await writeFile(join(clean.work,'base.txt'),'local repair\n');
  await clean.prepare(two);
  assert.equal(await readFile(join(clean.work,'base.txt'),'utf8'),'local repair\n');
  const legacy = new Workspace(join(root,'legacy'),issue,'fixture',run);
  await legacy.prepare(two);
  await rm(join(legacy.root,'workspace-base.json'));
  await writeFile(join(legacy.root,'repair-restoration.json'),JSON.stringify({base:two,status:'restored'}));
  await legacy.git(['fetch','--no-tags','origin',one]);
  await writeFile(join(legacy.work,'base.txt'),'legacy repair\n');
  await legacy.prepare(two);
  assert.equal(await readFile(join(legacy.work,'base.txt'),'utf8'),'legacy repair\n');
  const untracked = new Workspace(join(root,'untracked'),issue,'fixture',run);
  await untracked.prepare(one); await writeFile(join(untracked.work,'notes.txt'),'retained\n');
  await assert.rejects(untracked.prepare(two),/local changes/);
  assert.equal(await readFile(join(untracked.work,'notes.txt'),'utf8'),'retained\n');
});
